b -= 8  # b = b - 8
print("Hasil b setelah pengurangan:", b)
#Shortcut operator kali
c = 4
c *= 3  # c = c * 3
print("Hasil c setelah perkalian:", c)
#Shortcut operator bagi
d = 15
d /= 5  # d = d / 5
print("Hasil d setelah pembagian:", d)
#Shortcut operator modulus
